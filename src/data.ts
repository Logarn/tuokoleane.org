const gallery = (id: string, descriptions: string[]): GalleryImage[] =>
  descriptions.map((description, index) => ({
    src: `/images/listings/${id}/0${index + 1}.jpg`,
    alt: `Representative scene: ${description}`,
  }));

const productGallery = (id: string, filenames: string[], descriptions: string[]): GalleryImage[] =>
  filenames.map((filename, index) => ({
    src: `/images/listings/${id}/${filename}`,
    alt: `Product photograph: ${descriptions[index]}`,
  }));

